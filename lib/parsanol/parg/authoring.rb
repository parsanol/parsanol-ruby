# frozen_string_literal: true

require "json"

module Parsanol
  module PARG
    # External test suites: *.pgtest files carrying the same test syntax
    # as the inline test section (accept / reject / example). Suites are
    # development-time corpora — they iterate a grammar against its
    # binding requirements without being embedded in the artifact.
    #
    #   suite smoke for entry identifier {
    #     accept "ISO 8601-1:2019"
    #     example "ISO/CD 12345" { stage: "draft20" }
    #   }
    module Suite
      module_function

      # Load every *.pgtest file in a directory.
      # Returns { suite_name => [Document::Test, ...] }.
      def load(dir)
        Dir.glob(File.join(dir, "*.pgtest")).to_h do |file|
          [File.basename(file, ".pgtest"), read_file(file)]
        end
      end

      def read_file(file)
        content = PARG.read_utf8(file).gsub(/^#[^\n]*\n/, "")
        header = content.match(/suite\s+\w+(?:\s+for\s+entry\s+(?<entry>\w+))?\s*\{/)
        unless header
          raise ParseError,
                "#{file}: expected 'suite <name> [for <entry>] { ... }'"
        end

        body = content[header.end(0)..].sub(/\}\s*\z/, "")
        document = Parser.new("grammar Suite version \"0.0.0\" {\n}\ntest {\n#{body}\n}\n").parse
        document.tests.map do |test|
          Document::Test.new(header[:entry] || test.entry, test.kind, test.input, test.expect)
        end
      end
    end

    # The binding-requirements schema: what a language-specific data model
    # must implement for an entry. Derived from the declared bindings plus
    # the observed example values.
    module Schema
      module_function

      def from_artifact(artifact)
        artifact.entries.to_h do |entry|
          entry_data = artifact.entry(entry)
          fields = entry_data["bindings"].to_h do |binding|
            requirements = {
              "type" => binding["type"],
              "card" => binding["card"] || "1",
            }
            requirements["preprocess"] = binding["preprocess"] if binding["preprocess"]
            [binding["path"], requirements]
          end
          examples = artifact.envelope.fetch("tests", [])
            .select { |test| (test["kind"] == "example" && test["entry"].nil?) || test["entry"] == entry }
            .map { |test| { "input" => test["input"], "captures" => test["expect"] } }
          [entry, { "root" => entry_data["root"], "fields" => fields, "examples" => examples }]
        end
      end

      # The bound model's shape: a nested type tree derived from the
      # binding paths (ruby#308 v2). Dot segments nest objects, a
      # `[]` segment is an array of objects (or of leaf values when
      # the array is itself the leaf), and the leaf carries the
      # binding's type and card (`0..1` = nullable, `*` cards arrive
      # through the array node itself).
      #
      #   shape({ "items[].n" => { "type" => "integer", "card" => "1" } })
      #   # => { "items" => { "kind" => "array",
      #   #                    "of" => { "n" => { "kind" => "leaf", "type" => "integer", "card" => "1" } } } }
      def shape(fields)
        root = {}
        fields.each do |path, requirements|
          segments = path.split(".")
          node = root
          segments.each_with_index do |segment, index|
            array = segment.end_with?("[]")
            name = array ? segment.delete_suffix("[]") : segment
            leaf = index == segments.length - 1
            if array && leaf
              node[name] = {
                "kind" => "array",
                "of" => { "kind" => "leaf", "type" => requirements["type"], "card" => requirements["card"] },
              }
              break
            end
            slot = (node[name] ||= array ? { "kind" => "array", "of" => {} } : {})
            node = array ? slot["of"] : slot
            next unless leaf

            slot.update("kind" => "leaf", "type" => requirements["type"], "card" => requirements["card"])
          end
        end
        root
      end

      # TypeScript materialization types: one interface per entry, one
      # interface per nested object node (v2: the interfaces mirror
      # the bound model's shape). Cards ending in * become arrays;
      # 0..1 becomes nullable.
      def to_typescript(schema)
        lines = ["// Generated by parsanol parg schema --ts — binding-requirements types."]
        schema.each do |entry, data|
          lines << ""
          emit_ts_interface(lines, ts_name(entry), shape(data["fields"]))
        end
        "#{lines.join("\n")}\n"
      end

      def emit_ts_interface(lines, name, node)
        nested = []
        lines << "export interface #{name} {"
        node.each do |prop, child|
          case child["kind"]
          when "array"
            element = child["of"]
            inner = element["kind"] == "leaf" ? ts_leaf(element) : ts_ref_name(name, prop)
            lines << "  #{ts_prop(prop)}: #{inner}[];"
            nested << [ts_ref_name(name, prop), element] unless element["kind"] == "leaf"
          when "leaf"
            lines << "  #{ts_prop(prop)}: #{ts_leaf(child)};"
          end
        end
        lines << "}"
        lines << ""
        nested.each { |inner, element| emit_ts_interface(lines, inner, element) }
      end

      def ts_leaf(leaf)
        base = ts_base(leaf["type"])
        if leaf["card"].to_s.end_with?("*")
          "#{base}[]"
        elsif leaf["card"] == "0..1"
          "#{base} | null"
        else
          base
        end
      end

      def ts_base(type)
        case type
        when "integer", "float" then "number"
        when "boolean" then "boolean"
        else "string"
        end
      end

      def ts_ref_name(parent, prop)
        "#{parent}#{ts_prop(prop).split('.').map(&:capitalize).join}"
      end

      # Ruby materialization models: lutaml-model classes (the
      # established serialization framework — the generated file
      # requires it; the consumer's bundle carries the gem).
      def to_ruby(schema)
        lines = [
          "# frozen_string_literal: true",
          "",
          "# Generated by parsanol parg schema --ruby — lutaml-model binding types.",
          "require \"lutaml/model\"",
          "",
        ]
        schema.each do |entry, data|
          emit_ruby_class(lines, ts_name(entry), shape(data["fields"]))
        end
        "#{lines.join("\n")}\n"
      end

      def emit_ruby_class(lines, name, node)
        nested = []
        node.each do |prop, child|
          next unless child["kind"] == "array" && child["of"]["kind"] != "leaf"

          inner = lutaml_ref_name(name, prop)
          nested << [inner, child["of"]]
        end
        # Ruby resolves the constant at class-body time: the nested
        # models precede their parents.
        nested.each { |inner, element| emit_ruby_class(lines, inner, element) }
        lines << "class #{name} < Lutaml::Model::Serializable"
        lines <<
          node.each do |prop, child|
            attr_name = ts_prop(prop)
            case child["kind"]
            when "array"
              element = child["of"]
              if element["kind"] == "leaf"
                lines << "  attribute :#{attr_name}, #{lutaml_type(element)}, collection: true"
              else
                inner = lutaml_ref_name(name, prop)
                lines << "  attribute :#{attr_name}, #{inner}, collection: true"
                nested << [inner, element]
              end
            when "leaf"
              # lutaml-model attributes are nilable unless validated:
              # a 0..1 card is the plain attribute; presence-validated
              # cards are the consumer's policy, not the schema's.
              lines << "  attribute :#{attr_name}, #{lutaml_type(child)}"
            end
          end
        lines << "end"
        lines << ""
      end

      def lutaml_type(leaf)
        case leaf["type"]
        when "integer" then ":integer"
        when "float" then ":float"
        when "boolean" then ":boolean"
        else ":string"
        end
      end

      def lutaml_ref_name(parent, prop)
        "#{parent}#{ts_prop(prop).split('.').map(&:capitalize).join}"
      end

      # Rust materialization structs (serde): one struct per nested
      # object node, i64/f64/bool/String leaves, Vec for arrays,
      # Option for 0..1.
      def to_rust(schema)
        lines = [
          "// Generated by parsanol parg schema --rust — serde binding types.",
          "",
        ]
        schema.each do |entry, data|
          emit_rust_struct(lines, ts_name(entry), shape(data["fields"]))
        end
        "#{lines.join("\n")}\n"
      end

      def emit_rust_struct(lines, name, node)
        nested = []
        lines << "#[derive(Debug, serde::Serialize, serde::Deserialize)]"
        lines << "pub struct #{name} {"
        node.each do |prop, child|
          field = ts_prop(prop)
          snake = field.gsub(/([A-Z])/) { "_#{Regexp.last_match(1).downcase}" }
          case child["kind"]
          when "array"
            element = child["of"]
            inner = element["kind"] == "leaf" ? rust_leaf(element) : rust_ref_name(name, prop)
            lines << "    pub #{snake}: Vec<#{inner}>,"
            nested << [rust_ref_name(name, prop), element] unless element["kind"] == "leaf"
          when "leaf"
            base = rust_leaf(child)
            lines << "    pub #{snake}: #{child['card'] == '0..1' ? "Option<#{base}>" : base},"
          end
        end
        lines << "}"
        lines << ""
        nested.each { |inner, element| emit_rust_struct(lines, inner, element) }
      end

      def rust_leaf(leaf)
        case leaf["type"]
        when "integer" then "i64"
        when "float" then "f64"
        when "boolean" then "bool"
        else "String"
        end
      end

      def rust_ref_name(parent, prop)
        ts_ref_name(parent, prop)
      end

      def ts_name(entry)
        entry.split(/[_.]/).map(&:capitalize).join
      end

      def ts_prop(path)
        leaf = path.include?("[]") ? path.split("].").last : path
        leaf.gsub(/([A-Za-z0-9])_([a-z])/) do
          "#{Regexp.last_match(1)}#{Regexp.last_match(2).upcase}"
        end
      end

      def ts_type(requirements)
        base = case requirements["type"]
               when "integer", "float" then "number"
               when "boolean" then "boolean"
               else "string"
               end
        if requirements["card"].to_s.end_with?("*")
          "#{base}[]"
        elsif requirements["card"] == "0..1"
          "#{base} | null"
        else
          base
        end
      end
    end
  end
end
